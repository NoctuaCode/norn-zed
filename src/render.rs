use crate::{calendar::Date, schedule::{self, Status, Task}};
use std::collections::BTreeMap;
use std::fmt::Write as _;

pub const MARKER: &str = "<!-- Generated by zed-timeline; do not edit. -->";
const HOUR: u32 = 3600;
const SLOT: u32 = 900;

struct Axis {
    start: u32,
    end: u32,
}

impl Axis {
    fn for_tasks<'a>(tasks: impl Iterator<Item = &'a Task<'a>>) -> Option<Self> {
        let (mut start, mut end) = (u32::MAX, 0);
        for task in tasks {
            if let Some(range) = &task.range {
                start = start.min(range.start);
                end = end.max(range.end);
            }
        }
        (end > 0).then(|| Self { start: start / HOUR * HOUR, end: end.div_ceil(HOUR) * HOUR })
    }

    fn write_axis(&self, out: &mut String, width: usize) {
        let _ = write!(out, "    {:width$}", "");
        for hour in self.start / HOUR..self.end / HOUR {
            let _ = write!(out, "{hour:02}  ");
        }
        let _ = writeln!(out, "{:02}", self.end / HOUR);
    }

    fn lanes(&self, tasks: &[Task<'_>]) -> Vec<(String, u32)> {
        let mut lanes = Vec::<(String, u32)>::new();
        for task in tasks {
            let Some(range) = &task.range else { continue };
            let left = (range.start - self.start) / SLOT;
            let right = (range.end - self.start).div_ceil(SLOT);
            let row = lanes.iter().position(|(_, tail)| *tail <= left).unwrap_or(lanes.len());
            if row == lanes.len() {
                lanes.push((String::new(), 0));
            }
            let (text, tail) = &mut lanes[row];
            text.extend(std::iter::repeat_n(' ', (left - *tail) as usize));
            text.extend(std::iter::repeat_n('█', (right - left) as usize));
            *tail = right;
        }
        lanes
    }

    fn slots(&self) -> u32 {
        (self.end - self.start) / SLOT
    }
}

pub fn document(title: &str, notes: &[(Date, String)]) -> String {
    let mut out = format!("{MARKER}\n\n# {title}\n\n");
    let days: Vec<_> = notes.iter().map(|(date, text)| (*date, schedule::parse(text))).collect();
    let axis = Axis::for_tasks(days.iter().flat_map(|(_, tasks)| tasks));
    if let [(_, tasks)] = days.as_slice() {
        render_day(&mut out, tasks, axis.as_ref());
    } else {
        render_period(&mut out, &days, axis.as_ref());
    }
    render_project_totals(&mut out, days.iter().flat_map(|(_, tasks)| tasks));
    out
}

#[derive(Default)]
struct Duration {
    scheduled: u64,
    done: u64,
}

impl Duration {
    fn add(&mut self, seconds: u64, done: bool) {
        self.scheduled += seconds;
        if done {
            self.done += seconds;
        }
    }

    fn write(&self, out: &mut String, prefix: &str, label: &str) {
        let _ = write!(out, "{prefix}");
        for (seconds, suffix) in [(self.scheduled, " / "), (self.done, "  ")] {
            let _ = write!(
                out, "{:02}:{:02}:{:02}{suffix}", seconds / 3600, seconds / 60 % 60, seconds % 60
            );
        }
        for (index, word) in label.split_whitespace().enumerate() {
            if index != 0 {
                out.push(' ');
            }
            out.push_str(word);
        }
        out.push('\n');
    }
}

#[derive(Default)]
struct Project<'a> {
    duration: Duration,
    tasks: BTreeMap<String, (&'a str, Duration)>,
}

fn render_project_totals<'a>(out: &mut String, tasks: impl Iterator<Item = &'a Task<'a>>) {
    let mut projects = BTreeMap::<&str, Project<'_>>::new();
    for task in tasks {
        let Some(range) = task.range.as_ref().filter(|_| task.status != Status::Canceled) else {
            continue;
        };
        let (project, description) = match task.label.split_once(':') {
            Some((prefix, description)) if !prefix.is_empty() => (prefix.trim(), description.trim()),
            _ => ("", task.label),
        };
        let project = projects.entry(if project.is_empty() { "Unassigned" } else { project }).or_default();
        let description = if description.is_empty() { "(No description)" } else { description };
        let key = description.split_whitespace().flat_map(|word| [' '].into_iter().chain(word.chars()))
            .skip(1).flat_map(char::to_lowercase).collect::<String>();
        let (_, detail) = project.tasks.entry(key).or_insert_with(|| (description, Duration::default()));
        let seconds = u64::from(range.end - range.start);
        let done = task.status == Status::Done;
        detail.add(seconds, done);
        project.duration.add(seconds, done);
    }
    if projects.is_empty() {
        return;
    }
    out.push_str("\n## Project time (scheduled / marked done)\n\n");
    for (name, project) in projects {
        project.duration.write(out, "    ", name);
        let mut tasks = project.tasks.into_values().peekable();
        while let Some((label, duration)) = tasks.next() {
            let prefix = if tasks.peek().is_some() { "      ├─ " } else { "      └─ " };
            duration.write(out, prefix, label);
        }
    }
}

fn render_day(out: &mut String, tasks: &[Task<'_>], axis: Option<&Axis>) {
    if tasks.is_empty() {
        out.push_str("No task yet\n");
        return;
    }
    if let Some(axis) = axis {
        axis.write_axis(out, 19);
        for task in tasks {
            let Some(range) = &task.range else { continue };
            let left = (range.start - axis.start) / SLOT;
            let right = (range.end - axis.start).div_ceil(SLOT);
            let time = format!("{}–{}", range.from, range.to);
            let _ = write!(out, "    {time:17}  ");
            out.extend(std::iter::repeat_n(' ', left as usize));
            out.extend(std::iter::repeat_n('█', (right - left) as usize));
            out.extend(std::iter::repeat_n(' ', (axis.slots() - right) as usize));
            let _ = writeln!(out, "  │ {:8}  {}", task.status.label(), task.label);
        }
    } else {
        out.push_str("No timed tasks.\n");
    }
    if tasks.iter().any(|task| task.range.is_none()) {
        out.push_str("\n## Untimed tasks\n\n");
        for task in tasks.iter().filter(|task| task.range.is_none()) {
            let _ = write!(out, "- **{}** — ", task.status.label());
            if task.invalid {
                out.push_str("Invalid schedule: ");
            }
            for c in task.label.chars() {
                if c.is_ascii_punctuation() {
                    out.push('\\');
                }
                out.push(c);
            }
            out.push('\n');
        }
    }
}

fn render_period(out: &mut String, days: &[(Date, Vec<Task<'_>>)], axis: Option<&Axis>) {
    if let Some(axis) = axis {
        axis.write_axis(out, 12);
    }
    for (date, tasks) in days {
        let _ = write!(out, "    {date}  ");
        if let Some(axis) = axis {
            let lanes = axis.lanes(tasks);
            let (text, tail) = lanes.first().map_or(("", 0), |(text, tail)| (text.as_str(), *tail));
            out.push_str(text);
            out.extend(std::iter::repeat_n(' ', (axis.slots() - tail) as usize));
            out.push_str("  │ ");
            write_summary(out, tasks);
            for (text, _) in lanes.iter().skip(1) {
                let _ = writeln!(out, "    {:12}{text}", "");
            }
        } else {
            write_summary(out, tasks);
        }
    }
}

fn write_summary(out: &mut String, tasks: &[Task<'_>]) {
    if tasks.is_empty() {
        out.push_str("No task yet\n");
    } else {
        let done = tasks.iter().filter(|task| task.status == Status::Done).count();
        let _ = writeln!(out, "{done}/{} done", tasks.len());
    }
}
